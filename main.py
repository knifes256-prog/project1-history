def show_timeline(events):
    eras = []
    for _, era, _, _ in events:
        if era not in eras:
            eras.append(era)
    chosen = st.multiselect("시대 필터", eras, default=eras)
    last_era = None
    for year, era, title, desc in events:
        if era not in chosen:
            continue
        if era != last_era:
            st.markdown(f"#### 🏛️ {era}")
            last_era = era
        c1, c2 = st.columns([1, 4])
        c1.markdown(f"**{year}**")
        c2.markdown(f"**{title}**  \n{desc}")


