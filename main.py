def flag_emoji(iso3):
    """ISO-3 국가 코드에서 국기 이모지를 만듭니다."""
    country = pycountry.countries.get(alpha_3=iso3)
    if not country or not getattr(country, "alpha_2", None):
        return "🌐"
    return "".join(chr(127397 + ord(ch)) for ch in country.alpha_2.upper())

